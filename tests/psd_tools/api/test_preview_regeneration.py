"""What ``save()`` writes into the merged image data section (#866).

The section is regenerated whenever the document is marked updated, and it used
to be regenerated by rendering the composite to a PIL image and splitting that.
A PIL image describes PIL: one byte per channel whatever the header's depth
says, only the channels its mode has a letter for, a bit set the other way
round in mode ``"1"``, its own web palette in mode ``"P"``, an inverted
``"CMYK"``, and -- since the render applies the document's ICC profile -- an
sRGB copy of a document whose profile resource is still attached.

So a 16-bit document got a section half its declared length, which neither
psd-tools nor Photoshop can read back; a document with spot channels lost them;
and an 8-bit one came back with the right *shape* and the wrong pixels. The
planes are built from the compositor's arrays now, in the document's own
channels, depth and conventions, which is what these measure.
"""

